"""Controlled local artifacts: native CBM/declarative JSON, no Python deserialization.

The caller must provide its explicitly configured private registry outside the
workspace. Registry receipts pin bytes generated by this application. A hash chain
detects accidental changes; it is not authentication against someone able to rewrite
the trusted directory. OS access control remains part of the trust boundary.
"""

import hashlib
import json
import os
import re
import stat
from contextlib import contextmanager
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path
from typing import Annotated, Literal, Self
from uuid import UUID, uuid4

from forestcheck.domain.contracts import Contract, Digest, Text
from pydantic import AwareDatetime, Field, JsonValue, StrictInt, model_validator

MAX_JSON_BYTES = 4 * 1024 * 1024
MAX_MODEL_BYTES = 128 * 1024 * 1024
MAX_TOTAL_BYTES = 512 * 1024 * 1024
MAX_LEDGER_BYTES = 16 * 1024 * 1024
_NAME = re.compile(r"[A-Za-z0-9][A-Za-z0-9_.-]{0,79}\.(?:cbm|json)\Z")


def _canonical(value) -> bytes:
    return json.dumps(
        value, sort_keys=True, separators=(",", ":"), ensure_ascii=False, allow_nan=False
    ).encode("utf-8")


def _digest(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _unique_object(pairs):
    result = {}
    for name, value in pairs:
        if name in result:
            raise ValueError("duplicate_json_key")
        result[name] = value
    return result


def _json(data: bytes):
    if len(data) > MAX_JSON_BYTES:
        raise ValueError("json_size_limit")
    try:
        return json.loads(
            data,
            object_pairs_hook=_unique_object,
            parse_constant=lambda _: (_ for _ in ()).throw(ValueError("nonfinite_json")),
        )
    except (UnicodeError, RecursionError) as exc:
        raise ValueError("invalid_json") from exc


class ArtifactMetadata(Contract):
    method_id: Text
    config: dict[str, JsonValue]
    library_versions: Annotated[dict[str, Text], Field(min_length=1)]
    seed: StrictInt
    record_schema_version: Literal["1.0"]
    mapping_version: Text
    mapping_sha256: Digest
    split_sha256: Digest
    train_sha256: Digest
    features: Annotated[tuple[Text, ...], Field(min_length=1)]
    feature_lineage_sha256: Digest
    target: Text
    target_unit: Text
    dev_cohort_sha256: Digest
    dev_report: dict[str, JsonValue]
    source_kind: Literal["real_observation", "synthetic"]
    feedback_sha256: Digest | None = None

    @model_validator(mode="after")
    def consistent(self) -> Self:
        if len(self.features) != len(set(self.features)) or self.target in self.features:
            raise ValueError("invalid_feature_allowlist")
        _canonical(self.model_dump(mode="json"))
        return self


class ArtifactCompatibility(Contract):
    record_schema_version: Literal["1.0"]
    mapping_version: Text
    mapping_sha256: Digest
    features: tuple[Text, ...]
    target: Text
    target_unit: Text
    library_versions: dict[str, Text] = Field(default_factory=dict)


class _Manifest(Contract):
    model_id: UUID
    created_at: AwareDatetime
    metadata: ArtifactMetadata
    output_sha256: Annotated[dict[str, Digest], Field(min_length=1, max_length=16)]


class _RegistryIdentity(Contract):
    registry_id: UUID
    created_at: AwareDatetime
    policy: Literal["application_generated_native_and_declarative_only"]


class _Event(Contract):
    sequence: Annotated[int, Field(strict=True, ge=1)]
    action: Literal["register", "promote", "rollback"]
    model_id: UUID
    created_at: AwareDatetime
    previous_sha256: Digest
    event_sha256: Digest
    manifest_sha256: Digest | None
    expected_current: UUID | None
    reason: Text


@dataclass(frozen=True)
class VerifiedArtifact:
    model_id: UUID
    metadata: ArtifactMetadata
    model_files: dict[str, bytes]
    directory: Path

    def path(self, name: str) -> Path:
        """Recheck known bytes immediately before a native library path loader."""
        if name not in self.model_files:
            raise ValueError("unknown_model_file")
        _directory(self.directory)
        result = self.directory / name
        if _read_file(result, MAX_MODEL_BYTES) != self.model_files[name]:
            raise ValueError("artifact_integrity_failure")
        return result


def _ordinary(path: Path, directory=False):
    info = path.lstat()
    if (
        stat.S_ISLNK(info.st_mode)
        or getattr(info, "st_file_attributes", 0) & 0x400
        or (not directory and (not stat.S_ISREG(info.st_mode) or info.st_nlink != 1))
        or (directory and not stat.S_ISDIR(info.st_mode))
    ):
        raise ValueError("ordinary_file_or_directory_required")
    return info


def _directory(root: Path) -> Path:
    root = Path(root)
    if not root.is_absolute():
        raise ValueError("absolute_trusted_root_required")
    if ".." in root.parts:
        raise ValueError("path_traversal")
    for component in (root, *root.parents):
        _ordinary(component, directory=True)
    return root


def _read_file(path: Path, limit: int) -> bytes:
    info = _ordinary(path)
    if info.st_size > limit:
        raise ValueError("artifact_size_limit")
    with path.open("rb") as stream:
        content = stream.read(limit + 1)
    if len(content) > limit:
        raise ValueError("artifact_size_limit")
    return content


def _write_new(path: Path, data: bytes):
    with path.open("xb") as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())


def initialize_registry(trusted_root: Path) -> None:
    """Explicit initialization of an empty, caller-controlled directory only."""
    root = _directory(trusted_root)
    if any(root.iterdir()):
        raise ValueError("empty_controlled_directory_required")
    identity = _RegistryIdentity(
        schema_version="1.0",
        registry_id=uuid4(),
        created_at=datetime.now(timezone.utc),
        policy="application_generated_native_and_declarative_only",
    )
    _write_new(root / "registry.json", _canonical(identity.model_dump(mode="json")))
    _write_new(root / "registry.jsonl", b"")


def _registry(trusted_root: Path) -> tuple[Path, list[_Event]]:
    root = _directory(trusted_root)
    try:
        _RegistryIdentity.model_validate(_json(_read_file(root / "registry.json", MAX_JSON_BYTES)))
        data = _read_file(root / "registry.jsonl", MAX_LEDGER_BYTES)
    except FileNotFoundError as exc:
        raise ValueError("controlled_registry_required") from exc
    events = []
    previous = "0" * 64
    registered = set()
    active = None
    promoted = set()
    for index, line in enumerate(data.splitlines(), 1):
        if not line:
            raise ValueError("registry_integrity_failure")
        event = _Event.model_validate(_json(line))
        payload = event.model_dump(mode="json", exclude={"event_sha256"})
        if (
            event.sequence != index
            or event.previous_sha256 != previous
            or _digest(_canonical(payload)) != event.event_sha256
        ):
            raise ValueError("registry_integrity_failure")
        if event.action == "register":
            if (
                event.model_id in registered
                or event.manifest_sha256 is None
                or event.expected_current is not None
            ):
                raise ValueError("registry_integrity_failure")
            registered.add(event.model_id)
        else:
            if (
                event.model_id not in registered
                or event.manifest_sha256 is not None
                or event.expected_current != active
                or (event.action == "rollback" and event.model_id not in promoted)
            ):
                raise ValueError("registry_integrity_failure")
            active = event.model_id
            promoted.add(active)
        events.append(event)
        previous = event.event_sha256
    return root, events


@contextmanager
def _lock(root: Path):
    lock_path = root / "registry.lock"
    try:
        stream = lock_path.open("xb")
    except FileExistsError as exc:
        raise ValueError("registry_busy_or_interrupted_writer") from exc
    try:
        with stream:
            stream.write(b"local-writer")
            stream.flush()
            yield
    finally:
        _ordinary(lock_path)
        lock_path.unlink()


def _append(
    root: Path,
    events: list[_Event],
    *,
    action: str,
    model_id: UUID,
    manifest_sha256: str | None = None,
    expected_current: UUID | None = None,
    reason: str,
) -> None:
    payload = dict(
        schema_version="1.0",
        sequence=len(events) + 1,
        action=action,
        model_id=str(model_id),
        created_at=datetime.now(timezone.utc).isoformat(),
        previous_sha256=events[-1].event_sha256 if events else "0" * 64,
        manifest_sha256=manifest_sha256,
        expected_current=str(expected_current) if expected_current else None,
        reason=reason,
    )
    normalized = _Event.model_validate(dict(payload, event_sha256="0" * 64))
    payload = normalized.model_dump(mode="json", exclude={"event_sha256"})
    event = _Event.model_validate(dict(payload, event_sha256=_digest(_canonical(payload))))
    line = _canonical(event.model_dump(mode="json")) + b"\n"
    ledger = root / "registry.jsonl"
    if _ordinary(ledger).st_size + len(line) > MAX_LEDGER_BYTES:
        raise ValueError("registry_size_limit")
    with ledger.open("ab") as stream:
        stream.write(line)
        stream.flush()
        os.fsync(stream.fileno())


def register_candidate(
    trusted_root: Path, metadata: ArtifactMetadata, model_files: dict[str, bytes]
) -> UUID:
    root, _ = _registry(trusted_root)
    metadata = ArtifactMetadata.model_validate(metadata.model_dump(mode="json"))
    if not 1 <= len(model_files) <= 16:
        raise ValueError("model_file_count")
    total = 0
    for name, content in model_files.items():
        if not _NAME.fullmatch(name) or name in {"manifest.json", "registry.json"}:
            raise ValueError("unsupported_or_unsafe_model_file")
        if not isinstance(content, bytes) or not content or len(content) > MAX_MODEL_BYTES:
            raise ValueError("model_file_bytes_limit")
        total += len(content)
        if name.endswith(".json"):
            _json(content)
    if total > MAX_TOTAL_BYTES:
        raise ValueError("model_total_size_limit")
    with _lock(root):
        _, events = _registry(root)
        model_id = uuid4()
        directory = root / str(model_id)
        directory.mkdir()
        for name, data in model_files.items():
            _write_new(directory / name, data)
        manifest = _Manifest(
            schema_version="1.0",
            model_id=model_id,
            created_at=datetime.now(timezone.utc),
            metadata=metadata,
            output_sha256={name: _digest(data) for name, data in model_files.items()},
        )
        manifest_data = _canonical(manifest.model_dump(mode="json"))
        if len(manifest_data) > MAX_JSON_BYTES:
            raise ValueError("manifest_size_limit")
        _write_new(directory / "manifest.json", manifest_data)
        _append(
            root,
            events,
            action="register",
            model_id=model_id,
            manifest_sha256=_digest(manifest_data),
            reason="explicit_training_run_candidate",
        )
    return model_id


def _load(root: Path, events: list[_Event], model_id: UUID) -> VerifiedArtifact:
    model_id = UUID(str(model_id))
    registration = next(
        (event for event in events if event.action == "register" and event.model_id == model_id),
        None,
    )
    if registration is None:
        raise ValueError("unregistered_model")
    directory = root / str(model_id)
    _ordinary(directory, directory=True)
    data = _read_file(directory / "manifest.json", MAX_JSON_BYTES)
    if _digest(data) != registration.manifest_sha256:
        raise ValueError("manifest_integrity_failure")
    manifest = _Manifest.model_validate(_json(data))
    if manifest.model_id != model_id:
        raise ValueError("model_identity_integrity_failure")
    if {path.name for path in directory.iterdir()} != {*manifest.output_sha256, "manifest.json"}:
        raise ValueError("unexpected_artifact_files")
    files = {}
    total = 0
    for name, expected_digest in manifest.output_sha256.items():
        if not _NAME.fullmatch(name) or name in {"manifest.json", "registry.json"}:
            raise ValueError("unsupported_or_unsafe_model_file")
        content = _read_file(directory / name, MAX_MODEL_BYTES)
        total += len(content)
        if _digest(content) != expected_digest:
            raise ValueError("artifact_integrity_failure")
        if name.endswith(".json"):
            _json(content)
        files[name] = content
    if total > MAX_TOTAL_BYTES:
        raise ValueError("model_total_size_limit")
    return VerifiedArtifact(model_id, manifest.metadata, files, directory)


def load_candidate(
    trusted_root: Path, model_id: UUID, expected: ArtifactCompatibility
) -> VerifiedArtifact:
    root, events = _registry(trusted_root)
    artifact = _load(root, events, model_id)
    expected = ArtifactCompatibility.model_validate(expected.model_dump(mode="json"))
    for key in (
        "record_schema_version",
        "mapping_version",
        "mapping_sha256",
        "features",
        "target",
        "target_unit",
    ):
        if getattr(artifact.metadata, key) != getattr(expected, key):
            raise ValueError("incompatible_model_contract")
    if any(
        artifact.metadata.library_versions.get(key) != version
        for key, version in expected.library_versions.items()
    ):
        raise ValueError("incompatible_library_version")
    return artifact


def _current(events: list[_Event]) -> UUID | None:
    return next((event.model_id for event in reversed(events) if event.action != "register"), None)


def current_version(trusted_root: Path) -> UUID | None:
    _, events = _registry(trusted_root)
    return _current(events)


def _change_current(
    trusted_root: Path,
    model_id: UUID,
    *,
    expected_current: UUID | None,
    manual_confirmation: bool,
    reason: str,
    action: str,
):
    if manual_confirmation is not True:
        raise ValueError("manual_confirmation_required")
    if not isinstance(reason, str) or not reason.strip():
        raise ValueError("manual_reason_required")
    root, _ = _registry(trusted_root)
    with _lock(root):
        _, events = _registry(root)
        if _current(events) != expected_current:
            raise ValueError("stale_current_version")
        candidate = _load(root, events, model_id)
        if action == "rollback" and not any(
            event.model_id == model_id and event.action != "register" for event in events
        ):
            raise ValueError("rollback_requires_previously_promoted_version")
        if expected_current is not None:
            current = _load(root, events, expected_current)
            comparison_keys = (
                "split_sha256",
                "dev_cohort_sha256",
                "target",
                "target_unit",
                "record_schema_version",
                "mapping_sha256",
                "mapping_version",
                "source_kind",
            )
            if any(
                getattr(current.metadata, key) != getattr(candidate.metadata, key)
                for key in comparison_keys
            ):
                raise ValueError("incomparable_dev_experiments")
        _append(
            root,
            events,
            action=action,
            model_id=model_id,
            expected_current=expected_current,
            reason=reason,
        )


def promote(
    trusted_root: Path,
    model_id: UUID,
    *,
    expected_current: UUID | None,
    manual_confirmation: bool,
    reason: str,
) -> None:
    """Human decision only; no automatic promotion based on a favorable dev metric."""
    _change_current(
        trusted_root,
        model_id,
        expected_current=expected_current,
        manual_confirmation=manual_confirmation,
        reason=reason,
        action="promote",
    )


def rollback(
    trusted_root: Path,
    model_id: UUID,
    *,
    expected_current: UUID | None,
    manual_confirmation: bool,
    reason: str,
) -> None:
    """Append a return to a previously active compatible version; keep all history."""
    _change_current(
        trusted_root,
        model_id,
        expected_current=expected_current,
        manual_confirmation=manual_confirmation,
        reason=reason,
        action="rollback",
    )
